import type { IconName } from '../components/icons';

export interface PhotoSpec {
  /** Путь к реальному фото в /public/images. Пока пусто — рендерится заглушка. */
  src?: string;
  /** Путь к WebP-версии того же кадра (опционально, для source[type=webp]). */
  srcWebp?: string;
  /** Осмысленный alt. Используется и как aria-label заглушки. */
  alt: string;
  /** Что должно быть в кадре — техзадание фотографу. */
  spec: string;
}

